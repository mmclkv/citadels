'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { fixture, connect, until, wait } = require('./agent-harness.js');

test('missing model configuration rejects Agent creation while normal NPC remains available', async t => {
  const f = await fixture(false); t.after(f.close);
  const c = await connect(f.base, 'host'); t.after(c.close);
  const health = await (await fetch(f.base + '/api/agent/status')).json();
  assert.equal(health.configured, false); assert(!JSON.stringify(health).includes('mock-only-secret'));
  assert.equal((await fetch(f.base + '/%2e%2e%2fserver.js')).status, 403, 'server-only files cannot escape static mount');
  c.send({ t: 'createRoom', config: { bots: 1, botType: 'agent' } });
  await until(() => c.messages.some(m => m.t === 'error'), 'unconfigured rejection');
  assert.equal(c.state, null); assert.equal(f.mock.requests.length, 0);
  c.send({ t: 'createRoom', config: { playerCount: 4, bots: 1 } });
  await until(() => c.state && c.state.phase === 'lobby', 'ordinary room');
  c.send({ t: 'startGame' });
  await until(() => c.state.phase === 'draft', 'ordinary start');
  assert.equal(c.state.players.length, 4, 'empty seats must actually be filled');
  assert.equal(c.state.players.filter(p => p.isBot).length, 3);
});

test('multiplayer Agent waits for HTTP, pauses on failure, retries, and drops restarted answers', async t => {
  const f = await fixture(); t.after(f.close);
  const a = await connect(f.base, 'host'), b = await connect(f.base, 'guest');
  t.after(a.close); t.after(b.close);
  a.send({ t: 'createRoom', config: { playerCount: 4, bots: 1, botType: 'agent', botPace: 15 } });
  await until(() => a.state, 'created');
  b.send({ t: 'joinRoom', roomId: a.state.roomId, name: 'guest' });
  await until(() => b.state, 'joined');
  b.send({ t: 'setSeat', index: 1, kind: 'bot', botType: 'npc' });
  await until(() => b.messages.some(m => m.t === 'error'), 'non-host rejected');
  a.send({ t: 'setSeat', index: 1, kind: 'bot', botType: 'npc' });
  await until(() => a.state.seats[1].botType === 'npc', 'switch to ordinary even when room default is agent');
  a.send({ t: 'setSeat', index: 1, kind: 'bot', botType: 'agent' });
  await until(() => a.state.seats[1].botType === 'agent', 'switch to agent');
  f.mock.mode = 'error'; f.mock.delay = 150;
  a.send({ t: 'startGame' });
  await until(() => a.state.phase === 'draft', 'started');
  assert.equal(a.state.players.length, 4);
  assert.equal(a.state.players[3].botType, 'agent', 'auto-filled seat inherits Agent type');
  a.send({ t: 'action', action: a.state.available.actions[0] });
  await until(() => a.state.agentStatus && a.state.agentStatus.state === 'thinking', 'thinking status');
  const step = a.state.draft.stepIdx;
  await wait(40); assert.equal(a.state.draft.stepIdx, step, 'no action before model returns');
  await until(() => a.state.agentStatus.state === 'error', 'model error');
  assert.match(a.state.agentStatus.message, /401/);
  await wait(80); assert.equal(f.mock.requests.length, 1, 'no silent retry or NPC fallback');
  assert.equal(a.state.draft.stepIdx, step);
  assert(!JSON.stringify(a.messages).includes('private upstream diagnostic'));
  assert(!JSON.stringify(a.messages).includes('mock-only-secret'));
  f.mock.mode = 'ok'; f.mock.delay = 10;
  a.send({ t: 'agentControl', mode: 'retry' });
  await until(() => a.state.draft.stepIdx > step, 'model retry advances');
  assert.equal(a.state.players[1].hasChosen, true);
  assert.equal(f.mock.requests.length, 2);
  f.mock.delay = 300;
  await until(() => b.state.available.actions.length, 'guest turn');
  b.send({ t: 'action', action: b.state.available.actions[0] });
  await until(() => f.mock.requests.length === 3, 'second bot thinking');
  a.send({ t: 'restart' });
  await until(() => a.state.phase === 'lobby', 'restart');
  await wait(350);
  assert.equal(a.state.phase, 'lobby', 'old model response cannot change restarted room');
  f.mock.mode = 'error'; f.mock.delay = 0;
  a.send({ t: 'startGame' });
  await until(() => a.state.phase === 'draft', 'second game');
  a.send({ t: 'action', action: a.state.available.actions[0] });
  await until(() => a.state.agentStatus && a.state.agentStatus.state === 'error', 'second model failure');
  const calls = f.mock.requests.length;
  a.send({ t: 'agentControl', mode: 'npc' });
  await until(() => a.state.players[1].botType === 'npc' && a.state.players[1].hasChosen, 'explicit NPC switch');
  assert.equal(f.mock.requests.length, calls, 'NPC switch no longer calls model');
});
